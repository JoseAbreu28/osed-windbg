const esbuild = require("esbuild");
const { execSync } = require("child_process");
const pkg = require("./package.json");

function readGitValue(command, fallback) {
  try {
    return execSync(command, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || fallback;
  } catch (_error) {
    return fallback;
  }
}

const gitCommit = readGitValue("git rev-parse --short=12 HEAD", "unknown");
const gitStatus = readGitValue("git status --porcelain", "");

const fs = require("fs");
const path = require("path");
const { createLegacyTransformer } = require("./legacy/bigint_transform.js");
const { findEngineGaps, formatGaps } = require("./legacy/engine.js");

// sc.builder prints tools/sc_builder.py; regenerate its embedded copy so the two cannot drift.
const builderSource = fs.readFileSync(path.join(__dirname, "tools", "sc_builder.py"), "utf8").replace(/\r\n/g, "\n");
const builderModule = `// Generated by build.js from tools/sc_builder.py. Edit that file, then run npm run build.\nexport const SC_BUILDER_SOURCE = ${JSON.stringify(builderSource)};\n`;
const builderTarget = path.join(__dirname, "src", "shellcode", "sc_builder_source.ts");
if (!fs.existsSync(builderTarget) || fs.readFileSync(builderTarget, "utf8") !== builderModule) fs.writeFileSync(builderTarget, builderModule);

const legacyBigInt = {
  name: "legacy-bigint",
  setup(build) {
    const legacy = createLegacyTransformer(__dirname, ["src"]);
    build.onLoad({ filter: /\.ts$/ }, (args) => (legacy.has(args.path) ? { contents: legacy.transformFile(args.path), loader: "ts" } : undefined));
  },
};

const targets = [
  { outfile: "dist/osed.js", plugins: [] },
  {
    outfile: "dist/osed-legacy.js",
    plugins: [legacyBigInt],
    banner: { js: fs.readFileSync(path.join(__dirname, "legacy", "runtime.js"), "utf8") },
  },
];

function buildOptions(target) {
  return {
    entryPoints: [path.join(__dirname, "src", "index.ts")],
    outfile: path.join(__dirname, target.outfile),
    plugins: target.plugins,
    banner: target.banner,
    bundle: true,
    platform: "neutral",
    target: ["es2017"],
    format: "iife",
    globalName: "osed_bundle",
    footer: {
      js: [
        "var __osed_global = (typeof globalThis !== 'undefined') ? globalThis : (typeof self !== 'undefined' ? self : (typeof this !== 'undefined' ? this : undefined));",
        "if (__osed_global && __osed_global.osed_bundle && __osed_global.osed_bundle.initializeScript) { __osed_global.initializeScript = __osed_global.osed_bundle.initializeScript; }",
      ].join("\n"),
    },
    sourcemap: false,
    external: [],
    define: {
      __OSED_VERSION__: JSON.stringify(pkg.version),
      __OSED_BUILD_TIME__: JSON.stringify(new Date().toISOString()),
      __OSED_GIT_COMMIT__: JSON.stringify(gitCommit),
      __OSED_GIT_DIRTY__: JSON.stringify(gitStatus.length > 0),
    },
    logLevel: "info",
  };
}

function checkLegacyBundle(file) {
  const gaps = findEngineGaps(fs.readFileSync(file, "utf8"), file);
  if (gaps.length === 0) return;
  fs.unlinkSync(file);
  throw new Error(`${file} uses what classic WinDbg 10.0.19041 lacks (see legacy/engine.js); output deleted:\n${formatGaps(gaps)}`);
}

module.exports = { buildOptions, legacyTarget: targets[1] };

if (require.main === module) {
  Promise.all(targets.map((target) => esbuild.build(buildOptions(target))))
    .then(() => checkLegacyBundle(path.join(__dirname, targets[1].outfile)))
    .catch((error) => {
      console.error(error);
      process.exit(1);
    });
}
