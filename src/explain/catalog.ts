/**
 * Plain-language explanations for every command reachable from @$osed(). Each <name> in a text
 * field is a placeholder for an argument or a result of the same name; explain fills it from the
 * real call. tests/explain.test.ts fails when a command has no entry or a placeholder is unknown.
 */

export type ExplainArg = {
  name: string;
  meaning: string;
  optional?: boolean;
  default?: string;
  /** address prints as hex, number as decimal; anything else prints as given. */
  kind?: "address" | "number";
  /** Collects this and every later argument, as for sc.template tasks. */
  rest?: boolean;
  /** Meaning of known values. A key that ends in "=" or a space matches every value with that prefix. */
  values?: Record<string, string>;
};

export type ExplainResult = {
  name: string;
  meaning: string;
  /** A column of the first dx row or a field of the first finding; see resultValue in explain.ts. */
  field: string;
  kind?: "address" | "number";
};

export type ExplainEntry = {
  name: string;
  aliases?: string[];
  summary: string;
  what: string;
  how: string;
  when: string;
  args: ExplainArg[];
  results?: ExplainResult[];
  example: string;
  output: string;
  report: string;
  /** Read-only and fast: explain("name", args...) may run it silently to fill the results. */
  quick?: boolean;
  /** Field that holds a primitive return value; success unless the boolean means something else. */
  primitive?: "success" | "value";
};

